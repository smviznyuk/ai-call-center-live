import pg from 'pg';

const { Pool } = pg;

const DATABASE_URL = process.env.DATABASE_URL;

if (!DATABASE_URL) {
  throw new Error('Missing DATABASE_URL.');
}

const isLocalDatabase = /localhost|127\.0\.0\.1/i.test(DATABASE_URL);

const pool = new Pool({
  connectionString: DATABASE_URL,
  ssl: isLocalDatabase ? false : { rejectUnauthorized: false },
});

function cleanText(value) {
  if (typeof value !== 'string') return null;
  const cleaned = value.trim();
  return cleaned || null;
}

function normalizePhoneForStorage(value) {
  const raw = cleanText(value);
  if (!raw) return null;

  if (raw.startsWith('+')) {
    const digits = raw.replace(/\D/g, '');
    return digits ? `+${digits}` : null;
  }

  const digits = raw.replace(/\D/g, '');
  if (digits.length === 10) return `+1${digits}`;
  if (digits.length === 11 && digits.startsWith('1')) return `+${digits}`;
  return null;
}

export async function initDatabase() {
  const client = await pool.connect();

  try {
    await client.query('BEGIN');

    await client.query(`
      CREATE TABLE IF NOT EXISTS customers (
        id BIGSERIAL PRIMARY KEY,
        phone_e164 TEXT UNIQUE,
        name TEXT,
        email TEXT,
        default_address TEXT,
        default_zip TEXT,
        preferred_language TEXT,
        thumbtack_customer_id TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    await client.query(`
      ALTER TABLE customers
        ADD COLUMN IF NOT EXISTS thumbtack_customer_id TEXT
    `);

    // Thumbtack can send a useful lead without exposing a phone number.
    // Keep phone nullable so those leads can still have a Customer record.
    await client.query(`
      ALTER TABLE customers
        ALTER COLUMN phone_e164 DROP NOT NULL
    `).catch(() => {});

    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS customers_thumbtack_customer_id_uidx
      ON customers (thumbtack_customer_id)
      WHERE thumbtack_customer_id IS NOT NULL
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS jobs (
        job_number BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
        customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
        source TEXT NOT NULL DEFAULT 'phone',
        category TEXT,
        problem_summary TEXT,
        equipment_type TEXT,
        urgency TEXT,
        status TEXT NOT NULL DEFAULT 'open',
        service_address TEXT,
        service_zip TEXT,
        requested_start TIMESTAMPTZ,
        requested_time_text TEXT,
        requested_time_minutes INTEGER,
        confirmed_start TIMESTAMPTZ,
        service_fee_cents INTEGER NOT NULL DEFAULT 9500,
        callback_at_caller_number BOOLEAN,
        callback_phone TEXT,
        diagnosis TEXT,
        work_performed TEXT,
        total_cents INTEGER,
        amount_paid_cents INTEGER,
        payment_status TEXT,
        twilio_call_sid TEXT,
        thumbtack_negotiation_id TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    const jobColumns = [
      ['requested_time_text', 'TEXT'],
      ['requested_time_minutes', 'INTEGER'],
      ['callback_at_caller_number', 'BOOLEAN'],
      ['callback_phone', 'TEXT'],
      ['thumbtack_negotiation_id', 'TEXT'],
    ];

    for (const [column, type] of jobColumns) {
      await client.query(
        `ALTER TABLE jobs ADD COLUMN IF NOT EXISTS ${column} ${type}`
      );
    }

    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS jobs_twilio_call_sid_uidx
      ON jobs (twilio_call_sid)
      WHERE twilio_call_sid IS NOT NULL
    `);

    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS jobs_thumbtack_negotiation_id_uidx
      ON jobs (thumbtack_negotiation_id)
      WHERE thumbtack_negotiation_id IS NOT NULL
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS appointments (
        id BIGSERIAL PRIMARY KEY,
        job_number BIGINT NOT NULL REFERENCES jobs(job_number) ON DELETE CASCADE,
        requested_start TIMESTAMPTZ,
        confirmed_start TIMESTAMPTZ,
        status TEXT NOT NULL DEFAULT 'requested',
        notes TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS payments (
        id BIGSERIAL PRIMARY KEY,
        job_number BIGINT NOT NULL REFERENCES jobs(job_number) ON DELETE CASCADE,
        amount_cents INTEGER NOT NULL,
        method TEXT,
        status TEXT,
        reference TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS job_events (
        id BIGSERIAL PRIMARY KEY,
        job_number BIGINT NOT NULL REFERENCES jobs(job_number) ON DELETE CASCADE,
        event_type TEXT NOT NULL,
        details JSONB NOT NULL DEFAULT '{}'::jsonb,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS job_events_job_number_created_idx
      ON job_events (job_number, created_at)
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS transcript_chunks (
        id BIGSERIAL PRIMARY KEY,
        job_number BIGINT NOT NULL REFERENCES jobs(job_number) ON DELETE CASCADE,
        speaker TEXT NOT NULL,
        text TEXT NOT NULL,
        start_ms BIGINT,
        end_ms BIGINT,
        event_id TEXT,
        openai_session_id TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS transcript_chunks_job_number_id_idx
      ON transcript_chunks (job_number, id)
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS transcript_turns (
        id BIGSERIAL PRIMARY KEY,
        job_number BIGINT NOT NULL REFERENCES jobs(job_number) ON DELETE CASCADE,
        speaker TEXT NOT NULL,
        text TEXT NOT NULL,
        openai_session_id TEXT,
        turn_key TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS transcript_turns_job_turn_key_uidx
      ON transcript_turns (job_number, turn_key)
      WHERE turn_key IS NOT NULL
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS transcript_turns_job_number_id_idx
      ON transcript_turns (job_number, id)
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS call_transcripts (
        job_number BIGINT PRIMARY KEY REFERENCES jobs(job_number) ON DELETE CASCADE,
        readable_text TEXT NOT NULL DEFAULT '',
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        finalized_at TIMESTAMPTZ
      )
    `);

    // Raw webhook audit trail. It is intentionally separate from Jobs so we
    // can inspect Thumbtack payloads without losing fields we do not map yet.
    await client.query(`
      CREATE TABLE IF NOT EXISTS thumbtack_webhook_events (
        event_key TEXT PRIMARY KEY,
        event_type TEXT,
        negotiation_id TEXT,
        message_id TEXT,
        raw_payload JSONB NOT NULL,
        received_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS thumbtack_webhook_events_negotiation_idx
      ON thumbtack_webhook_events (negotiation_id, received_at)
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS thumbtack_leads (
        negotiation_id TEXT PRIMARY KEY,
        job_number BIGINT REFERENCES jobs(job_number) ON DELETE SET NULL,
        customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
        thumbtack_customer_id TEXT,
        business_id TEXT,
        thumbtack_status TEXT,
        category_name TEXT,
        customer_display_name TEXT,
        phone_e164 TEXT,
        city TEXT,
        state TEXT,
        zip_code TEXT,
        requested_time_text TEXT,
        lead_price JSONB,
        raw_payload JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS thumbtack_leads_job_number_idx
      ON thumbtack_leads (job_number)
    `);

    await client.query(`
      CREATE TABLE IF NOT EXISTS thumbtack_messages (
        message_id TEXT PRIMARY KEY,
        negotiation_id TEXT NOT NULL,
        job_number BIGINT REFERENCES jobs(job_number) ON DELETE SET NULL,
        sender TEXT,
        text TEXT,
        sent_at TIMESTAMPTZ,
        raw_payload JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS thumbtack_messages_negotiation_sent_idx
      ON thumbtack_messages (negotiation_id, sent_at, created_at)
    `);

    await client.query('COMMIT');
    console.log('Database initialized');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

export async function findOrCreateCustomer(phoneE164) {
  const normalizedPhone = normalizePhoneForStorage(phoneE164) || cleanText(phoneE164);

  if (!normalizedPhone) {
    throw new Error('findOrCreateCustomer requires a phone number.');
  }

  const existing = await pool.query(
    `SELECT * FROM customers WHERE phone_e164 = $1 LIMIT 1`,
    [normalizedPhone]
  );

  if (existing.rows[0]) return existing.rows[0];

  const inserted = await pool.query(
    `
      INSERT INTO customers (phone_e164)
      VALUES ($1)
      ON CONFLICT (phone_e164)
      DO UPDATE SET updated_at = NOW()
      RETURNING *
    `,
    [normalizedPhone]
  );

  return inserted.rows[0];
}

