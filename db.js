export async function updateCrmFromConversation({
  jobNumber,
  customerId,
  customerName,
  preferredLanguage,
  category,
  problemSummary,
  equipmentType,
  urgency,
  serviceAddress,
  serviceZip,
  requestedTimeText,
  callbackAtCallerNumber,
  callbackPhone,
}) {
  const client = await pool.connect();

  try {
    await client.query('BEGIN');

    const customerSets = [];
    const customerValues = [customerId];

    const addCustomer = (column, value) => {
      if (value === undefined || value === null || value === '') return;
      customerValues.push(value);
      customerSets.push(`${column} = $${customerValues.length}`);
    };

    addCustomer('name', cleanText(customerName));
    addCustomer('preferred_language', cleanText(preferredLanguage));
    addCustomer('default_address', cleanText(serviceAddress));
    addCustomer('default_zip', cleanText(serviceZip));

    if (customerId && customerSets.length) {
      customerSets.push('updated_at = NOW()');
      await client.query(
        `UPDATE customers SET ${customerSets.join(', ')} WHERE id = $1`,
        customerValues
      );
    }

    const jobSets = [];
    const jobValues = [jobNumber];

    const addJob = (column, value) => {
      if (value === undefined || value === null || value === '') return;
      jobValues.push(value);
      jobSets.push(`${column} = $${jobValues.length}`);
    };

    addJob('category', cleanText(category));
    addJob('problem_summary', cleanText(problemSummary));
    addJob('equipment_type', cleanText(equipmentType));
    addJob('urgency', cleanText(urgency));
    addJob('service_address', cleanText(serviceAddress));
    addJob('service_zip', cleanText(serviceZip));
    addJob('requested_time_text', cleanText(requestedTimeText));

    if (callbackAtCallerNumber === true || callbackAtCallerNumber === false) {
      addJob('callback_at_caller_number', callbackAtCallerNumber);
    }

    addJob('callback_phone', normalizePhoneForStorage(callbackPhone) || cleanText(callbackPhone));

    if (jobSets.length) {
      jobSets.push('updated_at = NOW()');
      await client.query(
        `UPDATE jobs SET ${jobSets.join(', ')} WHERE job_number = $1`,
        jobValues
      );
    }

    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

